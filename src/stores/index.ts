// ─── Proposal Store ────────────────────────────────────────────────

interface ProposalStore {
  proposals: Proposal[];
  selectedProposalId: string | null;
  setSelectedProposal: (id: string | null) => void;
  approveProposal: (id: string) => void;
  rejectProposal: (id: string) => void;
  addProposal: (p: Proposal) => void;
}

export const useProposalStore = create<ProposalStore>((set) => ({
  proposals: kernelConnected ? [] : createMockProposals(),
  selectedProposalId: null,

  setSelectedProposal: (id) => set({ selectedProposalId: id }),

  approveProposal: (id) => {
    if (kernelConnected) {
      kernelClient.approveProposal(id);
    }
    set((s) => ({
      proposals: s.proposals.map((p) =>
        p.id === id
          ? { ...p, status: 'canary' as const, deploymentPhase: 'canary' as const, deploymentProgress: 0, approvalBy: 'operator' }
          : p
      ),
    }));
  },

  rejectProposal: (id) => {
    if (kernelConnected) {
      kernelClient.rejectProposal(id);
    }
    set((s) => ({
      proposals: s.proposals.map((p) =>
        p.id === id ? { ...p, status: 'rejected' as const } : p
      ),
    }));
  },

  addProposal: (proposal) =>
    set((s) => ({
      proposals: [proposal, ...s.proposals],
    })),
}));

